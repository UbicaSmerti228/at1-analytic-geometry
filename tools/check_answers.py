#!/usr/bin/env python3
"""
Пересчёт всех числовых ответов курса: примеры модулей, пробник и тренировочный вариант.

Каждая проверка сравнивает ответ, написанный на сайте, с тем, что получается при честном вычислении.
Запуск:  python3 tools/check_answers.py   (или npm run check)
Код выхода 1, если хоть одна проверка не прошла.
"""
from fractions import Fraction as Fr
import math
import random

results = []


def ok(cond, msg):
    results.append((bool(cond), msg))


def close(a, b, eps=1e-3):
    return abs(a - b) < eps


def deg1(x, shown):
    """Угол в градусах, округлённый до десятых, совпадает с записанным на сайте."""
    return round(math.degrees(x), 1) == shown


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def norm(a):
    return math.sqrt(dot(a, a))


def det3(m):
    return dot(m[0], cross(m[1], m[2]))


def same_curve(f, g, k):
    """f(x, y) == k * g(x, y) в случайных точках — уравнения равносильны."""
    rnd = random.Random(1)
    return all(abs(f(x, y) - k * g(x, y)) < 1e-9 for x, y in ((rnd.uniform(-5, 5), rnd.uniform(-5, 5)) for _ in range(8)))



# ------------------------------------------------------------------ Модуль 0
ok((3 - 1, -1 - 2, 5 - (-1)) == (2, -3, 6), "0.1  AB = (2; −3; 6)")
ok(norm((2, -3, 6)) == 7, "0.1  |AB| = 7")
ok(((1 + 3) / 2, (2 - 1) / 2, (-1 + 5) / 2) == (2, 0.5, 2), "0.3  середина AB = (2; 0,5; 2)")
ok(Fr(2, -1) == Fr(-4, 2) == Fr(6, -3) == -2, "0.4  (2;−4;6) ∥ (−1;2;−3)")
ok(dot((1, 2, 2), (2, -1, 2)) == 4 and deg1(math.acos(4 / 9), 63.6), "0.2  cos φ = 4/9, φ ≈ 63,6°")
ok(dot((Fr(2, 3), 2, -1), (3, 1, 4)) == 0, "0.3  m = 2/3")
ok(3 * 4 - (-2) * 5 == 22 and det3(((1, 2, 3), (0, 1, 4), (2, 0, 1))) == 11, "0.4  определители 22 и 11")
ok(cross((2, 1, -1), (3, 5, 2)) == (7, -7, 7), "0.5  a × b = (7; −7; 7)")
ok(cross((1, 0, 0), (0, 1, 0)) == (0, 0, 1) and dot((1, -2, 3), (4, 5, 2)) == 0, "0    «Проверь себя»")

# ------------------------------------------------------------------ Модуль 1
ok(all(x - 2 * y + 4 == 0 for x, y in [(-2, 1), (4, 4)]), "1.1  x − 2y + 4 = 0 через A(−2;1), B(4;4)")
ok(3 * 2 + 4 * (-1) - 2 == 0, "1.2  3x + 4y − 2 = 0 через M(2;−1)")
ok(2 * 1 - 3 + 1 == 0, "1.3  2x − y + 1 = 0 через M(1;3)")
ok(3 * 1 - (-2) - 5 == 0 and 1 + 3 * (-2) + 5 == 0 and dot((3, -1), (1, 3)) == 0, "1.4  3x − y − 5 = 0 и x + 3y + 5 = 0")
x = Fr(-8, 5); y = 2 * x + 3
ok(close(5 / math.sqrt(50), 1 / math.sqrt(2)) and x - 3 * y + 1 == 0 and y == Fr(-1, 5), "1.5  φ = 45°, точка (−1,6; −0,2)")
ok(abs(3 * 3 + 4 * 4 - 5) / 5 == 4, "1.6  d = 4")

# ------------------------------------------------------------------ Модуль 2
ok(same_curve(lambda x, y: x * x + y * y - 4 * x + 6 * y - 3, lambda x, y: (x - 2) ** 2 + (y + 3) ** 2 - 16, 1), "2.1  окружность: центр (2;−3), R = 4")
ok(math.sqrt(25 - 16) == 3 and Fr(3, 5) == Fr(6, 10) and Fr(5) / Fr(3, 5) == Fr(25, 3), "2.1  16x²+25y²=400: c = 3, e = 0,6, x = ±25/3")
ok(Fr(9) / (1 - Fr(16, 25)) == 25, "2.2  малая ось 6, e = 4/5 → a² = 25")
ok(math.sqrt(16 + 9) == 5 and Fr(4) / Fr(5, 4) == Fr(16, 5), "2.3  9x²−16y²=144: c = 5, директрисы ±16/5")
ok(64 + 36 == 100 and Fr(6, 8) == Fr(3, 4), "2.4  гипербола x²/64 − y²/36 = 1")
ok(same_curve(lambda x, y: (x - 2) ** 2 + y * y - (x + 2) ** 2, lambda x, y: y * y - 8 * x, 1), "2.6  парабола y² = 8x по определению")
ok(same_curve(lambda x, y: 4 * x * x + 9 * y * y - 8 * x + 36 * y + 4, lambda x, y: (x - 1) ** 2 / 9 + (y + 2) ** 2 / 4 - 1, 36), "2.7  (x−1)²/9 + (y+2)²/4 = 1")
ok(same_curve(lambda x, y: y * y - 4 * y - 8 * x + 12, lambda x, y: (y - 2) ** 2 - 8 * (x - 1), 1), "2.8  (y−2)² = 8(x−1)")

# ------------------------------------------------------------------ Модули 3–5
ok(2 - 4 - 6 + 8 == 0, "3.1  x + 4y − 2z + 8 = 0")
ok(2 - 1 + 3 - 4 == 0, "3.2  2x − y + 3z − 4 = 0")
ok(cross((1, -1, -2), (2, 1, -1)) == (3, -3, 3) and all(x - y + z - 2 == 0 for x, y, z in [(1, 2, 3), (2, 1, 1), (3, 3, 2)]), "3.3  x − y + z − 2 = 0")
ok(Fr(abs(2 * 2 - 2 * 1 + (-1) + 3), 3) == Fr(4, 3), "3.4  d = 4/3")
ok((3 - 1, 0 + 2, 2 - 3) == (2, 2, -1), "4.1  s = (2; 2; −1)")
ok(cross((1, -2, 1), (2, 1, -1)) == (1, 3, 5) and 0 + 8 - 4 - 4 == 0 and 0 - 4 + 4 == 0, "4.2  x/1 = (y+4)/3 = (z+4)/5")
ok(Fr(dot((1, 1, 0), (0, 1, 1)), 2) == Fr(1, 2), "5.1  φ = 60°")
ok(dot((1, 2, -1), (3, -1, 1)) == 0 and det3(((-1, 5, -6), (1, 2, -1), (3, -1, 1))) == 21, "5.2  перпендикулярны и скрещиваются (смешанное = 21)")
t = 3
ok((1 + t) + (-1 + 2 * t) + (-t) - 6 == 0 and (1 + t, -1 + 2 * t, -t) == (4, 5, -3), "5.3  точка пересечения (4; 5; −3)")

# ------------------------------------------------------------------ Пробник
ok(2 * 2 + 3 - 7 == 0 and 2 * 1 + 5 - 7 == 0, "П1   2x + y − 7 = 0")
ok(round(math.sqrt(5) / 2, 3) == 1.118 and round(2 / (math.sqrt(5) / 2), 2) == 1.79, "П2   e = √5/2 ≈ 1,118, директрисы ≈ ±1,79")
ok(round(5 / math.sqrt(29), 2) == 0.93, "П3   d = 5/√29 ≈ 0,93")
ok((1 - 2, 5 - 3, 1 - 5) == (-1, 2, -4) and (2 - 1, 3 + 2, 5 - 4) == (1, 5, 1), "П4   x = 2 − t, y = 3 + 2t, z = 5 − 4t")
s, n = (2, 1, 2), (2, 1, -1)
ok(deg1(math.asin(abs(dot(s, n)) / (norm(s) * norm(n))), 24.1), "П5   φ = arcsin(1/√6) ≈ 24,1°")
A, B, C, M = (3, 6), (-3, 0), (5, 2), (1, 1)
ok(((B[0] + C[0]) // 2, (B[1] + C[1]) // 2) == M, "П6   M(1; 1)")
ok(5 * 3 - 2 * 6 - 3 == 0 and 5 * 1 - 2 * 1 - 3 == 0 and 4 * 3 + 6 - 18 == 0 and dot((1, -4), (8, 2)) == 0, "П6   медиана 5x − 2y − 3 = 0, высота 4x + y − 18 = 0")
ok(deg1(math.atan(13 / 18), 35.8) and deg1(math.acos(18 / math.sqrt(493)), 35.8), "П6   φ = arctg(13/18) ≈ 35,8° (двумя способами)")
hx, hy = Fr(69, 17), Fr(30, 17)
ok(4 * hx + hy - 18 == 0 and hx - 4 * hy + 3 == 0 and round(18 / math.sqrt(17), 2) == 4.37, "П6   H(69/17; 30/17), |AH| ≈ 4,37")
P = (Fr(19, 7), Fr(-3, 7), 0)
ok(cross((2, 1, -1), (3, 5, 2)) == (7, -7, 7) and 2 * P[0] + P[1] - P[2] == 5 and 3 * P[0] + 5 * P[1] + 2 * P[2] == 6, "П7   (x − 19/7)/1 = (y + 3/7)/(−1) = z/1")
f8 = lambda x, y: x * x + 2 * x - y * y + 4 * y + 1
ok(same_curve(f8, lambda x, y: (y - 2) ** 2 / 4 - (x + 1) ** 2 / 4 - 1, -4) and f8(-1, 0) == 0 and f8(-1, 4) == 0, "П8   (y−2)²/4 − (x+1)²/4 = 1, вершины (−1;0), (−1;4)")

# ------------------------------------------------------------------ Тренировочный вариант
ok(all(2 * x + y == 0 for x, y in [(-1, 2), (3, -6)]), "Т1   2x + y = 0")
ok(math.sqrt(25 - 9) == 4, "Т2   a = 5, b = 3, c = 4, e = 0,8")
ok(abs(2 * 1 - (-2) + 2 * 3 - 1) / 3 == 3, "Т3   d = 3")
ok((3 - 1, 1 + 2, -4 - 0) == (2, 3, -4), "Т4   s = (2; 3; −4)")
ok(dot((2, -1, 3), (1, 5, 1)) == 0 and 1 + 5 * (-1) + 0 - 7 != 0, "Т5   прямая параллельна плоскости")
ok(4 * (-2) + 3 * 6 - 10 == 0 and abs(3 * (-2) - 4 * 6 + 5) / 5 == 5 and deg1(math.atan(0.5), 26.6), "Т6   CH: 4x + 3y − 10 = 0, |CH| = 5, φ ≈ 26,6°")
ok(cross((1, 1, 1), (1, -1, -2)) == (-1, 3, -2) and 0 + 2 + 0 - 2 == 0 and 0 - 2 - 0 + 2 == 0, "Т7   x/(−1) = (y − 2)/3 = z/(−2)")
ok(same_curve(lambda x, y: x * x + 4 * y * y - 6 * x + 8 * y + 9, lambda x, y: (x - 3) ** 2 / 4 + (y + 1) ** 2 - 1, 4), "Т8   (x−3)²/4 + (y+1)² = 1")

# ------------------------------------------------------------------ Итог
for good, msg in results:
    print(("  ✓ " if good else "  ✗ ") + msg)
bad = sum(1 for good, _ in results if not good)
print(f"\nПроверок: {len(results)}, ошибок: {bad}")
raise SystemExit(1 if bad else 0)
